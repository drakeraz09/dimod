<script>
  import {onMount, tick} from 'svelte';
  import {_} from '../locales';
  import Section from './Section.svelte';
  import Button from './Button.svelte';
  import DropArea from './DropArea.svelte';
  import {progress, currentTask} from './stores';
  import {UserError} from '../common/errors';
  import {readAsArrayBuffer} from '../common/readers';
  import loadProject from '../packager/load-project';
  import {inspectProject, CLOUD_MESSAGE} from '../dimod/cloud-check';
  import Task from './task';
  import ImportingProject from './ImportProject.svelte';
  import importExternalProject from './import-external-project';

  let isImportingProject = false;
  importExternalProject({
    onStartImporting: () => {
      isImportingProject = true;
    },
    onCancelImporting: () => {
      isImportingProject = false;
    },
    onFinishImporting: (files) => {
      if (!isImportingProject) {
        // Import was cancelled.
        return;
      }
      isImportingProject = false;
      fileInputElement.files = files;
      setFiles(files);
    }
  });

  export let projectData = null;
  let notes = [];
  const resetProjectAndCancelTask = () => {
    projectData = null;
    notes = [];
    currentTask.abort();
  };

  let fileInputElement;

  const copyFileList = (files) => {
    const transfer = new DataTransfer();
    for (const file of files) {
      transfer.items.add(file);
    }
    return transfer.files;
  };

  // This is used to remember files between reloads in some browsers (currently only Firefox)
  // This element is defined in the HTML of template.ejs because some browsers won't
  // autocomplete file inputs generated by JS.
  const inputForRememberingProjectFile = document.querySelector('.input-for-remembering-project-file');
  if (inputForRememberingProjectFile) {
    // Check for autocompleted files after mount so that fileInputElement is defined.
    onMount(() => {
      const storedFiles = inputForRememberingProjectFile.files;
      if (storedFiles.length) {
        fileInputElement.files = copyFileList(storedFiles);
      }
    });
  }

  const setFiles = (files) => {
    resetProjectAndCancelTask();
    if (fileInputElement.files !== files) {
      fileInputElement.files = files;
    }
    if (inputForRememberingProjectFile) {
      inputForRememberingProjectFile.files = copyFileList(files);
    }
    if (files.length) {
      tick().then(load);
    }
  };
  const isProjectFileName = (name) => /\.(warp|sb3)$/i.test(name);
  const handleDrop = ({detail: dataTransfer}) => {
    const file = dataTransfer.files[0];
    if (file && isProjectFileName(file.name)) {
      setFiles(dataTransfer.files);
    }
  };
  const handleFileInputChange = (e) => {
    setFiles(e.target.files);
  };

  const internalLoad = async (task) => {
    const progressCallback = (type, a, b) => {
      if (type === 'fetch') {
        task.setProgress(a);
      } else if (type === 'assets') {
        task.setProgressText(
          $_('progress.loadingAssets')
            .replace('{complete}', a)
            .replace('{total}', b)
        );
        task.setProgress(a / b);
      } else if (type === 'compress') {
        task.setProgressText($_('progress.compressingProject'));
        task.setProgress(a);
      }
    };

    const files = fileInputElement.files;
    const file = files && files[0];
    if (!file) {
      throw new UserError($_('select.noFileSelected'));
    }
    if (!isProjectFileName(file.name)) {
      throw new UserError('That is not a Dimod project. Choose a .warp file: in the editor, File > Save to your computer.');
    }
    task.setProgressText($_('progress.compressingProject'));

    const inspection = await inspectProject(await readAsArrayBuffer(file));
    if (inspection.cloud) {
      throw new UserError(`${CLOUD_MESSAGE} Why: ${inspection.reasons.join(' ')}`);
    }
    notes = inspection.notes;

    const project = await (await loadProject.fromFile(file, progressCallback)).promise;
    return {
      projectId: null,
      uniqueId: `@${file.name}`,
      title: file.name.replace(/\.(warp|sb3)$/i, ''),
      project,
    };
  };
  const load = async () => {
    resetProjectAndCancelTask();
    const task = new Task();
    projectData = await task.do(internalLoad(task));
    task.done();
  };
</script>

<style>
  .options {
    margin: 12px 0;
  }
  .cloud-note {
    padding: 8px 10px;
    border-left: 4px solid #e17055;
    background: rgba(225, 112, 85, 0.1);
  }
  .note {
    font-size: 0.9em;
    opacity: 0.85;
  }
</style>

{#if isImportingProject}
  <ImportingProject on:cancel={() => {
    isImportingProject = false;
  }} />
{/if}

<DropArea on:drop={handleDrop}>
  <Section accent="#6c5ce7">
    <h2>Choose your project</h2>
    <p>
      Drop a <b>.warp</b> file here, or pick one. You can get one in Dimod's editor with
      File &gt; Save to your computer. If the project isn't yours, make sure to credit whoever made it.
    </p>
    <p class="cloud-note">
      <b>Cloud projects can't be packaged.</b> Their server code and database run on Dimod's game
      server, which a packaged project can't reach. Everything else, complex sprites and Dimod's own
      blocks included, works wherever you put it.
    </p>
    <div class="options">
      <input on:change={handleFileInputChange} bind:this={fileInputElement} type="file" accept=".warp,.sb3">
    </div>
    <Button on:click={load} text={$_('select.loadProject')} />
    {#each notes as note}
      <p class="note">{note}</p>
    {/each}
  </Section>
</DropArea>

{#if !$progress.visible && !projectData}
  <Section caption>
    <p>{$_('select.loadToContinue')}</p>
  </Section>
{/if}
